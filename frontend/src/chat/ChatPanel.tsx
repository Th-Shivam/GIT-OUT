import { ScrollView, StyleSheet, Text, View } from 'react-native';
import { AppButton, AppField, EmptyState, FieldLabel, SectionHeading, StatusPill, Surface } from '../ui/components';
import { theme } from '../ui/theme';

export interface ConversationEntry {
  id: string;
  prompt: string;
  response: string;
}

interface Props {
  prompt: string;
  onPromptChange(prompt: string): void;
  onGenerate(): void;
  onRetrySpeech(): void;
  response: string;
  history: ConversationEntry[];
  modelReady: boolean;
  working: boolean;
  canRetrySpeech: boolean;
}

export function ChatPanel({ prompt, onPromptChange, onGenerate, onRetrySpeech, response, history, modelReady, working, canRetrySpeech }: Props) {
  return (
    <View style={styles.content}>
      <SectionHeading eyebrow="Chat / local inference" title="Your working conversation" detail="Answers are generated by the GGUF model on this device. No prompt is sent to the GitHub service." />
      <Surface>
        <View style={styles.statusRow}>
          <Text style={styles.cardLabel}>Local model</Text>
          <StatusPill label={modelReady ? 'Ready' : 'Load in Settings'} tone={modelReady ? 'positive' : 'warning'} />
        </View>
        <FieldLabel>Prompt</FieldLabel>
        <AppField
          accessibilityLabel="Local AI prompt"
          multiline
          value={prompt}
          onChangeText={onPromptChange}
          placeholder="Ask about Git, code review, or your next implementation step"
          style={styles.prompt}
          textAlignVertical="top"
        />
        <AppButton label={working ? 'Generating locally…' : 'Generate answer'} onPress={onGenerate} disabled={!modelReady || working || !prompt.trim()} />
      </Surface>

      {response ? (
        <Surface raised>
          <View style={styles.statusRow}>
            <Text style={styles.cardLabel}>Git Out</Text>
            <Text style={styles.localLabel}>ON DEVICE</Text>
          </View>
          <Text selectable style={styles.answer}>{response}</Text>
          <AppButton label="Replay answer" onPress={onRetrySpeech} disabled={!canRetrySpeech || working} variant="secondary" />
        </Surface>
      ) : (
        <EmptyState title="No answer yet" detail="Your completed local answer will remain here for reading, copying, or replaying." />
      )}

      {history.length ? (
        <Surface>
          <Text style={styles.cardLabel}>Recent turns</Text>
          <ScrollView horizontal contentContainerStyle={styles.history} showsHorizontalScrollIndicator={false}>
            {history.slice(-5).map((entry) => (
              <View key={entry.id} style={styles.historyCard}>
                <Text numberOfLines={2} style={styles.historyPrompt}>{entry.prompt}</Text>
                <Text numberOfLines={3} style={styles.historyAnswer}>{entry.response}</Text>
              </View>
            ))}
          </ScrollView>
        </Surface>
      ) : null}
    </View>
  );
}

const styles = StyleSheet.create({
  content: { gap: theme.spacing.lg },
  statusRow: { alignItems: 'center', flexDirection: 'row', justifyContent: 'space-between' },
  cardLabel: { color: theme.colors.text, fontSize: theme.typography.heading, fontWeight: '800' },
  localLabel: { color: theme.colors.green, fontSize: theme.typography.label, fontWeight: '800', letterSpacing: 1 },
  prompt: { minHeight: 120 },
  answer: { color: theme.colors.text, fontSize: 16, lineHeight: 25 },
  history: { gap: theme.spacing.sm },
  historyCard: { backgroundColor: theme.colors.canvas, borderColor: theme.colors.border, borderRadius: theme.radius.md, borderWidth: 1, gap: theme.spacing.sm, padding: theme.spacing.md, width: 220 },
  historyPrompt: { color: theme.colors.text, fontSize: theme.typography.small, fontWeight: '700', lineHeight: 18 },
  historyAnswer: { color: theme.colors.textMuted, fontSize: theme.typography.small, lineHeight: 18 },
});
